void delay(int ms) {
    for (volatile int i = 0; i < ms * 209920; i++) {
        // no-op
    }
}

void play_sound(uint32_t freq) {
    if (freq == 0) return;

    uint32_t divisor = 1193180 / freq;

    // Command byte to set PIT channel 2, access mode lobyte/hibyte, mode 3 (square wave)
    out(0x43, 0xB6);

    // Set frequency divisor for channel 2
    out(0x42, (uint8_t)(divisor & 0xFF));         // Low byte
    out(0x42, (uint8_t)((divisor >> 8) & 0xFF));  // High byte

    // Enable the speaker by setting bits 0 and 1 at port 0x61
    uint8_t tmp = in(0x61);
    if ((tmp & 0x03) != 0x03) {
        out(0x61, tmp | 0x03);
    }
}

void play_melody(uint32_t* m, int length) {
    int notes = length / 2;
    for (int i = 0; i < notes; i++) {
        int note = m[i * 2];
        int duration = m[i * 2 + 1];
        if (note != REST) {
            play_sound(note);
        }
        delay(duration);
        nosound();
        delay(50);  // Short pause between notes
    }
}



void nosound() {
    // Clear bits 0 and 1 at port 0x61 to turn off the speaker
    uint8_t tmp = in(0x61) & 0xFC;
    out(0x61, tmp);
}

char* int_to_char(int num) {
    static char buffer[12];  // Enough space for 32-bit integer
    int i = 0;
    if (num == 0) {
        buffer[i++] = '0';
    } else {
        while (num > 0) {
            buffer[i++] = (num % 10) + '0';
            num /= 10;
        }
    }
    buffer[i] = '\0';

    // Reverse the string
    for (int j = 0; j < i / 2; j++) {
        char temp = buffer[j];
        buffer[j] = buffer[i - j - 1];
        buffer[i - j - 1] = temp;
    }
    return buffer;
}